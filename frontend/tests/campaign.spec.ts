import { test, expect } from '@playwright/test';
import path from 'node:path';

test('coloca el PNG del usuario, guarda la plantilla y la aplica de nuevo', async ({ page }) => {
  await page.goto('/');
  await expect(page.getByText('Motor local listo')).toBeVisible();
  await page.getByLabel('Seleccionar vídeo', { exact: true }).setInputFiles(path.resolve('../demo/clipzone-demo.mp4'));
  await expect(page.locator('.video-frame video')).toBeVisible();
  await page.getByRole('button', { name: 'Gráficos y plantillas', exact: true }).click();
  const panel = page.getByRole('region', { name: 'Gráficos y plantillas' });
  await panel.getByLabel('Plantilla de campaña').selectOption('example-kick');
  await panel.getByRole('button', { name: 'Aplicar plantilla' }).click();
  const layer = panel.locator('.graphic-row').filter({ hasText: 'Logo de Kick' });
  await layer.locator('summary').click();
  const buffer = Buffer.from('iVBORw0KGgoAAAANSUhEUgAAACAAAAAgCAYAAABzenr0AAAAMklEQVR4nO3OoQ0AAAgEMUb4/fdEwxAITC853+pkLtc1AAAAAAAAAAAAAAAAAACAb8ACcKcoPafsLX8AAAAASUVORK5CYII=', 'base64');
  await layer.getByLabel('PNG de la capa 1').setInputFiles({ name: 'Logo á.png', mimeType: 'image/png', buffer });
  await layer.getByRole('button', { name: 'Posicionar en el vídeo' }).click();
  const graphic = page.getByRole('button', { name: 'Mover Logo de Kick', exact: true });
  await expect(graphic.locator('img')).toBeVisible();
  await graphic.scrollIntoViewIfNeeded();
  const bounds = (await graphic.boundingBox())!;
  await page.mouse.move(bounds.x + bounds.width / 2, bounds.y + bounds.height / 2);
  await page.mouse.down();
  await page.mouse.move(bounds.x + bounds.width / 2 + 24, bounds.y + bounds.height / 2 + 15, { steps: 5 });
  await page.mouse.up();
  const moved = await layer.getByText('Horizontal (%)', { exact: true }).locator('input').inputValue();
  expect(+moved).toBeGreaterThan(15);
  await panel.getByLabel('Nombre de plantilla').fill('Mi campaña Kick');
  await panel.getByRole('button', { name: 'Guardar como plantilla' }).click();
  await expect(panel.getByText('Plantilla guardada.')).toBeVisible();
  await layer.getByRole('button', { name: 'Eliminar capa' }).click();
  await expect(graphic).toHaveCount(0);
  await panel.getByRole('button', { name: 'Aplicar plantilla' }).click();
  await expect(graphic.locator('img')).toBeVisible();
  await page.getByLabel('Resolución', { exact: true }).selectOption('480');
  await page.getByText('Ajuste de precisión', { exact: true }).click();
  await page.getByLabel('Salida en segundos').fill('1.5');
  await page.getByRole('button', { name: 'Vista exacta', exact: true }).click();
  await expect.poll(() => page.locator('.video-frame video').evaluate((video: HTMLVideoElement) => video.videoHeight)).toBe(854);
  await expect(graphic).toHaveCount(0);
});
